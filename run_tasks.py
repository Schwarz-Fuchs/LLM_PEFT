import argparse
import contextlib
from collections.abc import Mapping
import hashlib
import json
import os
import re
import subprocess
import sys
import traceback
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def atomic_write_json(path: Path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    temp_path = path.with_suffix(path.suffix + '.tmp')
    with temp_path.open('w', encoding='utf-8') as handle:
        json.dump(value, handle, indent=2, ensure_ascii=False)
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(temp_path, path)


def safe_name(value):
    cleaned = re.sub(r'[^A-Za-z0-9_.-]+', '_', str(value)).strip('._')
    return cleaned or 'task'


def _checkpoint_payload_is_readable(path):
    """Read a checkpoint payload on CPU to detect truncated/corrupt files."""
    if path.suffix == '.safetensors':
        from safetensors.torch import load_file
        payload = load_file(str(path), device='cpu')
    else:
        import torch
        # Checkpoints are locally generated by Trainer. weights_only=False is
        # required for optimizer/RNG payloads on supported PyTorch versions.
        payload = torch.load(str(path), map_location='cpu', weights_only=False)
    return isinstance(payload, Mapping) and bool(payload)


def validate_checkpoint(checkpoint_dir):
    """Return (is_valid, reason) for a resumable Trainer checkpoint.

    A PEFT checkpoint stores adapter weights only, but a true Trainer resume
    also needs the optimizer, scheduler, trainer state, and RNG state.
    """
    checkpoint_dir = Path(checkpoint_dir)
    match = re.fullmatch(r'checkpoint-(\d+)', checkpoint_dir.name)
    if not checkpoint_dir.is_dir() or not match:
        return False, 'not a checkpoint-N directory'

    model_files = ('model.safetensors', 'pytorch_model.bin',
                   'adapter_model.safetensors', 'adapter_model.bin')
    model_file = next(
        (checkpoint_dir / name for name in model_files
         if (checkpoint_dir / name).is_file() and (checkpoint_dir / name).stat().st_size > 0),
        None,
    )
    if model_file is None:
        return False, 'missing or empty model/adapter weights'
    try:
        if not _checkpoint_payload_is_readable(model_file):
            return False, f'empty or invalid weights payload: {model_file.name}'
    except Exception as exc:
        return False, f'unreadable weights payload {model_file.name} ({type(exc).__name__}: {exc})'

    trainer_state = checkpoint_dir / 'trainer_state.json'
    if not trainer_state.is_file() or trainer_state.stat().st_size == 0:
        return False, 'missing or empty trainer_state.json'
    try:
        with trainer_state.open('r', encoding='utf-8') as handle:
            state = json.load(handle)
        if int(state.get('global_step', -1)) != int(match.group(1)):
            return False, 'trainer_state global_step does not match checkpoint directory'
    except (OSError, ValueError, TypeError, json.JSONDecodeError) as exc:
        return False, f'invalid trainer_state.json ({exc})'

    for name in ('optimizer.pt', 'scheduler.pt'):
        path = checkpoint_dir / name
        if not path.is_file() or path.stat().st_size == 0:
            return False, f'missing or empty {name}'
        try:
            if not _checkpoint_payload_is_readable(path):
                return False, f'empty or invalid {name} payload'
        except Exception as exc:
            return False, f'unreadable {name} ({type(exc).__name__}: {exc})'

    rng_files = list(checkpoint_dir.glob('rng_state*.pth'))
    readable_rng = False
    for path in rng_files:
        if path.is_file() and path.stat().st_size > 0:
            try:
                if _checkpoint_payload_is_readable(path):
                    readable_rng = True
                    break
            except Exception:
                continue
    if not readable_rng:
        return False, 'missing, empty, or unreadable rng_state*.pth'

    return True, 'ok'


def latest_checkpoint(output_dir):
    """Choose the newest complete checkpoint, or fail closed if all are bad."""
    folder = Path(output_dir)
    checkpoints = []
    if folder.is_dir():
        for item in folder.glob('checkpoint-*'):
            match = re.fullmatch(r'checkpoint-(\d+)', item.name)
            if item.is_dir() and match:
                checkpoints.append((int(match.group(1)), item))

    if not checkpoints:
        return None

    invalid = []
    for step, path in sorted(checkpoints, reverse=True):
        valid, reason = validate_checkpoint(path)
        if valid:
            if invalid:
                print(f'[checkpoint] Skipping invalid newer checkpoint(s): '
                      + '; '.join(f'{name} ({why})' for name, why in invalid))
            return str(path.resolve())

        # Keep the incomplete data for inspection, but move it out of the
        # checkpoint-N namespace so Trainer cannot collide with it on resave.
        stamp = datetime.now(timezone.utc).strftime('%Y%m%dT%H%M%SZ')
        quarantine = path.with_name(f'{path.name}.incomplete-{stamp}')
        try:
            path.rename(quarantine)
            reason += f'; moved aside as {quarantine.name}'
        except OSError as exc:
            reason += f'; could not move aside ({exc})'
        invalid.append((path.name, reason))

    details = '; '.join(f'{name}: {why}' for name, why in invalid)
    raise RuntimeError(
        f'Found checkpoint directories in {folder}, but none is safe to resume: {details}. '
        'Training was stopped to avoid silently starting from scratch. '
        'Restore a valid checkpoint or move the incomplete checkpoint directories aside.'
    )


def run_training(task_id, config, record, run_dir, state, state_file):
    train_config = dict(config)
    output_dir = train_config.get('output_dir')
    if not output_dir:
        raise ValueError(f'{task_id}: training config requires output_dir')
    if train_config.get('resume_from_checkpoint') is None:
        checkpoint = latest_checkpoint(output_dir)
        if checkpoint:
            train_config['resume_from_checkpoint'] = checkpoint
            print(f'[{task_id}] Resuming from {checkpoint}')
        elif record.get('train_status') in ('running', 'failed'):
            raise RuntimeError(
                f'{task_id}: a previous training attempt was interrupted or failed, '
                f'but no valid checkpoint exists in {output_dir}. Refusing to silently '
                'restart from the beginning. To intentionally restart, use a new task_id '
                'and output_dir after preserving any files you need.'
            )

    record['train_status'] = 'running'
    record['train_started_at'] = datetime.now(timezone.utc).isoformat()
    record.pop('error', None)
    atomic_write_json(state_file, state)

    log_path = run_dir / 'logs' / f'{safe_name(task_id)}-train.log'
    log_path.parent.mkdir(parents=True, exist_ok=True)
    try:
        sys.path.insert(0, str(ROOT))
        from finetune import train
        with log_path.open('a', encoding='utf-8', buffering=1) as log:
            log.write(f'\n===== train start {datetime.now(timezone.utc).isoformat()} =====\n')
            with contextlib.redirect_stdout(log), contextlib.redirect_stderr(log):
                train(**train_config)
        record['train_status'] = 'completed'
        record['train_finished_at'] = datetime.now(timezone.utc).isoformat()
        record['train_log'] = str(log_path.relative_to(run_dir))
        atomic_write_json(state_file, state)
        return True
    except Exception as exc:
        with log_path.open('a', encoding='utf-8') as log:
            traceback.print_exc(file=log)
        record['train_status'] = 'failed'
        record['error'] = f'{type(exc).__name__}: {exc}'
        record['train_log'] = str(log_path.relative_to(run_dir))
        atomic_write_json(state_file, state)
        print(f'[{task_id}] training failed: {exc}; see {log_path}')
        return False
    finally:
        try:
            import gc
            import torch
            gc.collect()
            if torch.cuda.is_available():
                torch.cuda.empty_cache()
        except Exception:
            pass


def run_evaluation(task_id, eval_id, eval_config, eval_hash, train_config, run_dir, record, state, state_file):
    evaluation = dict(eval_config)
    if not evaluation.get('lora_weights'):
        if not train_config or not train_config.get('output_dir'):
            raise ValueError(f'{task_id}/{eval_id}: lora_weights required without a training output_dir')
        evaluation['lora_weights'] = train_config['output_dir']

    result_path = run_dir / 'results' / safe_name(task_id) / f'{safe_name(eval_id)}-{eval_hash[:10]}.json'
    result_path.parent.mkdir(parents=True, exist_ok=True)
    log_path = run_dir / 'logs' / f'{safe_name(task_id)}-{safe_name(eval_id)}-eval.log'
    log_path.parent.mkdir(parents=True, exist_ok=True)

    required = ('model', 'dataset', 'adapter', 'base_model', 'lora_weights')
    missing = [key for key in required if not evaluation.get(key)]
    if missing:
        raise ValueError(f'{task_id}/{eval_id}: missing evaluation fields: {missing}')

    command = [sys.executable, str(ROOT / 'evaluate.py')]
    for key in required:
        command.extend([f'--{key}', str(evaluation[key])])
    command.extend(['--output_file', str(result_path), '--resume'])
    if evaluation.get('load_8bit', False):
        command.append('--load_8bit')

    generation = evaluation.get('generation', {})
    allowed_generation = {
        'temperature', 'top_p', 'top_k', 'num_beams',
        'max_new_tokens', 'do_sample', 'use_cache',
    }
    unknown_generation = set(generation) - allowed_generation
    if unknown_generation:
        raise ValueError(f'{task_id}/{eval_id}: unsupported generation settings: {sorted(unknown_generation)}')
    for key in ('temperature', 'top_p', 'top_k', 'num_beams', 'max_new_tokens'):
        if key in generation:
            command.extend([f'--{key}', str(generation[key])])
    if generation.get('do_sample', False):
        command.append('--do_sample')
    if generation.get('use_cache') is False:
        command.append('--no_use_cache')

    eval_record = record.setdefault('evaluations', {}).setdefault(eval_id, {})
    eval_record['eval_sha256'] = eval_hash
    eval_record['status'] = 'running'
    eval_record['started_at'] = datetime.now(timezone.utc).isoformat()
    eval_record['result_file'] = str(result_path.relative_to(run_dir))
    atomic_write_json(state_file, state)
    with log_path.open('a', encoding='utf-8') as log:
        log.write(f'\n===== eval start {datetime.now(timezone.utc).isoformat()} =====\n')
        log.write('command: ' + subprocess.list2cmdline(command) + '\n')
        result = subprocess.run(command, cwd=ROOT, stdout=log, stderr=subprocess.STDOUT, check=False)

    eval_record['status'] = 'completed' if result.returncode == 0 else 'failed'
    eval_record['return_code'] = result.returncode
    eval_record['finished_at'] = datetime.now(timezone.utc).isoformat()
    eval_record['log'] = str(log_path.relative_to(run_dir))
    atomic_write_json(state_file, state)
    if result.returncode != 0:
        print(f'[{task_id}/{eval_id}] evaluation failed; see {log_path}')
        return False
    return True


def load_manifest(config_path):
    with config_path.open('r', encoding='utf-8-sig') as handle:
        manifest = json.load(handle)
    tasks = manifest.get('tasks')
    if not isinstance(tasks, list):
        raise ValueError('Task manifest must contain a "tasks" list')
    task_ids = [str(task.get('task_id', '')) for task in tasks]
    if any(not item for item in task_ids) or len(set(task_ids)) != len(task_ids):
        raise ValueError('Every task needs a unique, non-empty task_id')
    return manifest


def stable_digest(value):
    encoded = json.dumps(value, sort_keys=True, ensure_ascii=False).encode('utf-8')
    return hashlib.sha256(encoded).hexdigest()


def task_digest(task):
    # Evaluation settings can change independently without forcing retraining.
    return stable_digest({'task_id': str(task['task_id']), 'train': task.get('train')})


def eval_digest(evaluation):
    return stable_digest(evaluation)


def task_is_complete(task, record):
    train_complete = not task.get('train') or record.get('train_status') == 'completed'
    eval_records = record.get('evaluations', {})
    evaluations_complete = all(
        eval_records.get(str(item.get('eval_id') or item.get('dataset') or 'evaluation'), {}).get('status') == 'completed'
        and eval_records.get(str(item.get('eval_id') or item.get('dataset') or 'evaluation'), {}).get('eval_sha256') == eval_digest(item)
        for item in task.get('evaluations', [])
    )
    return train_complete and evaluations_complete


def main():
    parser = argparse.ArgumentParser(description='Run and resume multiple PEFT jobs.')
    parser.add_argument('--config', required=True, help='Path to a JSON task manifest')
    parser.add_argument('--run-dir', default='', help='Progress/log/result directory (default: runs/<run_name>)')
    args = parser.parse_args()

    config_path = Path(args.config)
    if not config_path.is_absolute():
        config_path = ROOT / config_path
    manifest = load_manifest(config_path)

    run_name = safe_name(manifest.get('run_name', config_path.stem))
    run_dir = Path(args.run_dir) if args.run_dir else ROOT / 'runs' / run_name
    if not run_dir.is_absolute():
        run_dir = ROOT / run_dir
    run_dir.mkdir(parents=True, exist_ok=True)
    state_file = run_dir / 'state.json'
    if state_file.exists():
        with state_file.open('r', encoding='utf-8-sig') as handle:
            state = json.load(handle)
        if state.get('run_name') != run_name:
            raise ValueError(f'{state_file} belongs to a different run_name')
        state.setdefault('tasks', {})
    else:
        state = {'schema_version': 2, 'run_name': run_name, 'tasks': {}}

    # Migrate task records from the earlier whole-manifest state format. Task IDs
    # are treated as immutable identifiers; use a new ID when changing a task.
    state['schema_version'] = 2

    def reload_manifest():
        latest = load_manifest(config_path)
        latest_run_name = safe_name(latest.get('run_name', config_path.stem))
        if latest_run_name != run_name:
            raise ValueError('Keep run_name unchanged while a batch is running')
        return latest

    for task in manifest['tasks']:
        task_id = str(task['task_id'])
        record = state['tasks'].setdefault(task_id, {'evaluations': {}})
        old_digest = record.get('task_sha256')
        current_digest = task_digest(task)
        legacy_digest = stable_digest(task)
        if old_digest and old_digest not in (current_digest, legacy_digest):
            raise ValueError(
                f'Training settings for task {task_id!r} changed after progress was recorded. '
                'Use a new task_id and output_dir for changed training settings.'
            )
        record['task_sha256'] = current_digest
    atomic_write_json(state_file, state)

    failures = 0
    abort_batch = False
    attempted_this_run = set()

    # Reload the manifest at each safe boundary. New tasks can be appended while
    # another task is running; removed pending tasks will not be started.
    while not abort_batch:
        manifest = reload_manifest()
        current_tasks = {str(task['task_id']): task for task in manifest['tasks']}
        removed_state_changed = False
        for saved_id, saved_record in state['tasks'].items():
            if saved_id not in current_tasks and saved_record.get('status') != 'completed':
                if saved_record.get('status') != 'removed':
                    saved_record['status'] = 'removed'
                    saved_record['removed_at'] = datetime.now(timezone.utc).isoformat()
                    removed_state_changed = True
        if removed_state_changed:
            atomic_write_json(state_file, state)
        selected = None
        for task in manifest['tasks']:
            task_id = str(task['task_id'])
            if task_id in attempted_this_run:
                continue
            record = state['tasks'].get(task_id, {})
            digest = task_digest(task)
            if record.get('task_sha256') and record['task_sha256'] != digest:
                raise ValueError(
                    f'Training settings for task {task_id!r} changed after progress was recorded. '
                    'Use a new task_id and output_dir for changed training settings.'
                )
            if task_is_complete(task, record):
                record['status'] = 'completed'
                continue
            selected = task
            break

        if selected is None:
            break

        task_id = str(selected['task_id'])
        attempted_this_run.add(task_id)
        record = state['tasks'].setdefault(task_id, {'evaluations': {}})
        record['task_sha256'] = task_digest(selected)
        record['status'] = 'running'
        record.pop('error', None)
        train_config = selected.get('train')
        evaluations = selected.get('evaluations', [])
        if not train_config and not evaluations:
            raise ValueError(f'{task_id}: provide a train block, evaluations, or both')
        atomic_write_json(state_file, state)

        if train_config and record.get('train_status') != 'completed':
            if not run_training(task_id, train_config, record, run_dir, state, state_file):
                failures += 1
                record['status'] = 'incomplete'
                atomic_write_json(state_file, state)
                if not manifest.get('continue_on_error', True):
                    break
                continue

        # If this task was removed while training was in progress, let the
        # current training phase finish safely, then omit its evaluations.
        latest_manifest = reload_manifest()
        latest_tasks = {str(task['task_id']): task for task in latest_manifest['tasks']}
        if task_id not in latest_tasks:
            record['status'] = 'removed'
            record['removed_at'] = datetime.now(timezone.utc).isoformat()
            atomic_write_json(state_file, state)
            print(f'[{task_id}] removed from task manifest; remaining stages skipped')
            continue
        if task_digest(latest_tasks[task_id]) != record['task_sha256']:
            raise ValueError(
                f'Task {task_id!r} changed while running. Keep its settings stable; '
                'use a new task_id for a revised task.'
            )

        task_failed = False
        attempted_evaluations = set()
        while not abort_batch:
            latest_manifest = reload_manifest()
            latest_tasks = {str(task['task_id']): task for task in latest_manifest['tasks']}
            if task_id not in latest_tasks:
                record['status'] = 'removed'
                record['removed_at'] = datetime.now(timezone.utc).isoformat()
                print(f'[{task_id}] removed from task manifest; remaining evaluations skipped')
                break
            current_task = latest_tasks[task_id]
            if task_digest(current_task) != record['task_sha256']:
                raise ValueError(
                    f'Training settings for task {task_id!r} changed while running. '
                    'Use a new task_id for revised training settings.'
                )

            evaluation = None
            eval_id = None
            for candidate in current_task.get('evaluations', []):
                candidate_id = str(candidate.get('eval_id') or candidate.get('dataset') or 'evaluation')
                candidate_hash = eval_digest(candidate)
                if (candidate_id, candidate_hash) in attempted_evaluations:
                    continue
                candidate_record = record.get('evaluations', {}).get(candidate_id, {})
                if candidate_record.get('status') == 'completed' and candidate_record.get('eval_sha256') == candidate_hash:
                    attempted_evaluations.add((candidate_id, candidate_hash))
                    continue
                evaluation = candidate
                eval_id = candidate_id
                break
            if evaluation is None:
                break

            evaluation_hash = eval_digest(evaluation)
            attempted_evaluations.add((eval_id, evaluation_hash))
            previous_eval = record.get('evaluations', {}).get(eval_id, {})
            if previous_eval.get('eval_sha256') != evaluation_hash:
                record.setdefault('evaluations', {})[eval_id] = {'eval_sha256': evaluation_hash}
            try:
                ok = run_evaluation(
                    task_id, eval_id, evaluation, evaluation_hash, train_config,
                    run_dir, record, state, state_file
                )
            except Exception as exc:
                record.setdefault('evaluations', {}).setdefault(eval_id, {})['status'] = 'failed'
                record['evaluations'][eval_id]['eval_sha256'] = evaluation_hash
                record['evaluations'][eval_id]['error'] = f'{type(exc).__name__}: {exc}'
                atomic_write_json(state_file, state)
                print(f'[{task_id}/{eval_id}] evaluation failed: {exc}')
                ok = False
            if not ok:
                failures += 1
                task_failed = True
                if not latest_manifest.get('continue_on_error', True):
                    abort_batch = True
                    break

        # Recheck deletion and task/evaluation changes before marking completion.
        latest_manifest = reload_manifest()
        latest_tasks = {str(task['task_id']): task for task in latest_manifest['tasks']}
        if task_id not in latest_tasks:
            record['status'] = 'removed'
            record['removed_at'] = datetime.now(timezone.utc).isoformat()
        elif task_failed:
            record['status'] = 'incomplete'
        else:
            record['status'] = 'completed' if task_is_complete(latest_tasks[task_id], record) else 'incomplete'
        atomic_write_json(state_file, state)

    # Also retain state for tasks removed before they were selected; they are
    # not deleted from state.json, so prior progress remains available.
    print(f'Batch run finished with {failures} failed job(s). State: {state_file}')
    return 1 if failures else 0

if __name__ == '__main__':
    raise SystemExit(main())

